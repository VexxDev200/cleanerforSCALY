"""Генерация scalyclean/_integrity.py перед PyInstaller."""

from __future__ import annotations

import hashlib
import hmac
import json
import secrets
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

WATCHED = (
    "main.py",
    "scalyclean/app.py",
    "scalyclean/core/protection.py",
    "scalyclean/core/updater.py",
    "scalyclean/core/update_config.py",
    "release_settings.json",
)


def _signing_key() -> bytes:
    raw = bytes(
        (
            0xF2,
            0x9C,
            0x11,
            0xA8,
            0x55,
            0x3E,
            0xC0,
            0x7D,
            0x18,
            0xB4,
            0x62,
            0x91,
            0x0F,
            0xD3,
            0x44,
            0xE6,
            0x29,
            0x5A,
            0x83,
            0x1C,
            0xAF,
            0x70,
            0x36,
            0xBB,
            0x4E,
            0x02,
            0x97,
            0x6D,
            0xCA,
            0x51,
            0x08,
            0xFE,
        )
    )
    return hashlib.sha256(raw).digest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def write_integrity_module() -> None:
    hashes: dict[str, str] = {}
    for rel in WATCHED:
        path = ROOT / rel
        if not path.is_file():
            raise FileNotFoundError(path)
        hashes[rel.replace("\\", "/")] = sha256_file(path)

    stamp = datetime.now(timezone.utc).strftime("%Y%m%d%H%M%S") + "-" + secrets.token_hex(4)
    payload = json.dumps(
        {"stamp": stamp, "files": hashes},
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    sig = hmac.new(_signing_key(), payload, hashlib.sha256).hexdigest()

    lines = [
        "# AUTO-GENERATED by tools/build_release.py — do not edit",
        f'BUILD_STAMP = "{stamp}"',
        f"FILE_HASHES = {json.dumps(hashes, indent=4)}",
        f'HMAC_SIG = "{sig}"',
        "",
    ]
    out = ROOT / "scalyclean" / "_integrity.py"
    out.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    write_integrity_module()
    print("Wrote scalyclean/_integrity.py")
